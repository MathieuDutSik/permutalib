// The word in GAP syntax with the generators F.1, F.2, ...
inline std::string GapStringWord(PresentationWord const &w,
                                 std::string const &F) {
  if (w.empty())
    return "One(" + F + ")";
  std::string ret;
  size_t i = 0;
  while (i < w.size()) {
    size_t j = i;
    while (j < w.size() && w[j] == w[i])
      j++;
    int e = static_cast<int>(j - i);
    if (w[i] < 0)
      e = -e;
    if (!ret.empty())
      ret += "*";
    ret += F + "." + std::to_string(std::abs(w[i]));
    if (e != 1)
      ret += "^" + std::to_string(e);
    i = j;
  }
  return ret;
}

// The GAP code of a record with the finitely presented group and the
// permutations of its generators.
template <typename Telt>
std::string GapStringPresentation(Presentation<Telt> const &P) {
  std::string F = "F";
  std::string ret = "local F, G;\n";
  ret += "F:=FreeGroup(" + std::to_string(P.generators.size()) + ");\n";
  ret += "G:=F/[";
  bool is_first = true;
  for (auto &r : P.relators) {
    if (!is_first)
      ret += ",";
    is_first = false;
    ret += "\n" + GapStringWord(r, F);
  }
  ret += "];\n";
  ret += "return rec(fp:=G, gens:=" + GapStringTVector(P.generators) + ");\n";
  return ret;
}

