#include "Permutation.h"
#include "gmpxx.h"
#include <fstream>

#include "Group.h"
#include "Resolution.h"

int main(int argc, char *argv[]) {
  try {
    using Tidx = uint16_t;
    using Telt = permutalib::SingleSidedPerm<Tidx>;
    using Tint = mpz_class;
    using Tgroup = permutalib::Group<Telt, Tint>;
    if (argc != 3 && argc != 4) {
      std::cerr << "The program is used as\n";
      std::cerr << "GapPresentation [EXMP] [generators|strong|resolution]\n";
      std::cerr << "or\n";
      std::cerr << "GapPresentation [EXMP] [generators|strong|resolution] [OutFile]\n";
      std::cerr << "with EXMP generated by GenerateExample.g\n";
      std::cerr << "generators: the presentation on the input generators, the "
                   "other strong generators eliminated\n";
      std::cerr << "strong: the presentation on the strong generators\n";
      std::cerr << "resolution: the presentation on the input generators "
                   "from the resolution of Resolution.h (small groups)\n";
      throw permutalib::PermutalibException{1};
    }
    std::string InputFile = argv[1];
    std::string choice = argv[2];
    //
    std::ifstream is(InputFile);
    std::pair<std::vector<Telt>, Telt> pair =
        permutalib::ReadListGenFromStream<Telt>(is);
    Tgroup eG(pair.first, pair.second);
    permutalib::Presentation<Telt> P;
    if (choice == "generators") {
      P = eG.PresentationOnGenerators();
    } else if (choice == "strong") {
      P = eG.PresentationOnStrongGenerators();
    } else if (choice == "resolution") {
      P = permutalib::PresentationByResolution<Telt, Tint>(pair.first,
                                                           pair.second);
    } else {
      std::cerr << "The choice should be generators, strong or resolution\n";
      throw permutalib::PermutalibException{1};
    }
    std::cerr << "CPP |gens|=" << P.generators.size()
              << " |rels|=" << P.relators.size()
              << " length=" << permutalib::TotalLength(P.relators) << "\n";
    //
    std::string str = permutalib::GapStringPresentation(P);
    if (argc == 4) {
      std::string OutputFile = argv[3];
      std::ofstream os(OutputFile);
      os << str;
    } else {
      std::cerr << str;
    }
    std::cerr << "CPP Normal completion of the program\n";
  } catch (permutalib::PermutalibException const &e) {
    std::cerr << "Erroneous completion of the program\n";
    exit(e.eVal);
  }
  return 0;
}
